"""Build Ostinato's icon fonts from Google's Material Icons.

    .venv/bin/python scripts/make_icon_font.py [~/material-design-icons]

Writes assets/icons_<size>.bin (LVGL binary fonts holding only the icons
listed in ICONS) and app/ui/icons.py (name -> character). An icon is then
just text in a label: crisp at its size and coloured by the theme. The icons
are Apache-2.0 (see assets/ICONS-LICENSE). Needs lv_font_conv, or npx to
fetch it.
"""

import os
import pathlib
import shutil
import subprocess
import sys

ICONS = [
    "play_arrow", "stop", "fiber_manual_record", "repeat", "add", "remove", "delete",
    "undo", "redo", "save", "folder_open", "file_download", "music_note", "piano",
    "tune", "graphic_eq", "volume_up", "volume_off", "headphones", "settings", "close",
    "more_vert", "content_copy", "grid_on", "queue_music", "timer", "speed", "keyboard",
    "equalizer", "mic", "edit", "expand_more", "chevron_left", "chevron_right", "usb",
    "memory", "check", "help_outline", "drag_indicator", "skip_previous", "layers",
    "power_settings_new", "auto_fix_high", "sensors", "album", "speaker", "expand_less",
]
SIZES = (20, 24, 32, 48)

ROOT = pathlib.Path(__file__).resolve().parent.parent


def main():
    src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/material-design-icons"))
    font = src / "font" / "MaterialIcons-Regular.ttf"
    codes = {}
    for line in (src / "font" / "MaterialIcons-Regular.codepoints").read_text().split("\n"):
        if line.strip():
            name, cp = line.split()
            codes.setdefault(name, int(cp, 16))
    missing = [n for n in ICONS if n not in codes]
    if missing:
        raise SystemExit("not in Material Icons: %s" % missing)
    conv = ["lv_font_conv"] if shutil.which("lv_font_conv") else ["npx", "--yes", "lv_font_conv"]
    ranges = ",".join("0x%X" % codes[n] for n in ICONS)
    for size in SIZES:
        out = ROOT / "assets" / ("icons_%d.bin" % size)
        subprocess.run(conv + ["--font", str(font), "--size", str(size), "--bpp", "4", "--format", "bin",
                               "--no-compress", "-r", ranges, "-o", str(out)], check=True)
        print(out.name, out.stat().st_size)
    lines = ['"""Material Icons as characters in Ostinato\'s icon fonts.', "",
             "Generated by scripts/make_icon_font.py; edit ICONS there, not here.", '"""', "",
             "SIZES = %r" % (SIZES,), "", "ICONS = {"]
    lines += ['    "%s": "\\u%04x",' % (n, codes[n]) for n in ICONS]
    lines += ["}", ""]
    (ROOT / "app" / "ui" / "icons.py").write_text("\n".join(lines))
    shutil.copy(src / "LICENSE", ROOT / "assets" / "ICONS-LICENSE")


if __name__ == "__main__":
    main()
