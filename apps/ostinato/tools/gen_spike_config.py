"""Write spike/pyscript.json and spike/spike_config.js from wheels.json and vendor/lib.

    .venv/bin/python tools/gen_spike_config.py

Run after scripts/fetch_wheels.py or scripts/fetch_midi.py.
"""

import json
import os
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent


def main():
    w = json.loads((ROOT / "wheels.json").read_text())
    ver = w["pydevices"]["version"]
    raw = "https://raw.githubusercontent.com/PyDevices/pydevices/v%s/board_configs/psdisplay/" % ver
    page = {
        "packages": ["/vendor/wheels/" + w[n]["file"] for n in ("pydevices", "pydevices-lvgl")],
        "files": {raw + "board_config.py": "./board_config.py", raw + "board_peripherals.py": "./board_peripherals.py"},
    }
    (ROOT / "spike" / "pyscript.json").write_text(json.dumps(page, indent=2) + "\n")
    libs = sorted(
        os.path.relpath(os.path.join(d, f), ROOT / "vendor" / "lib")
        for d, _, fs in os.walk(ROOT / "vendor" / "lib") for f in fs if f.endswith(".py"))
    engine = {
        "wheels": ["vendor/wheels/" + w[n]["file"] for n in
                   ("numpy", "omnipython-audiodsp", "omnipython-audioeffects", "omnipython-audioinstruments")],
        "libs": libs, "voice": "mono_synth", "parse": "adafruit", "target": 768,
        "lvglWheel": "vendor/wheels/" + w["pydevices-lvgl"]["file"],
    }
    (ROOT / "spike" / "spike_config.js").write_text(
        "// Generated by tools/gen_spike_config.py: what the engine worker loads.\nexport default "
        + json.dumps(engine, indent=2) + ";\n")


if __name__ == "__main__":
    main()
